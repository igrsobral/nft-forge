import { expect, test } from '@playwright/test'

test('signs in, checks out, and shows the confirmed receipt', async ({ page }) => {
  await page.goto('/?reset=1')
  await page.goto('/login')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('E-mail').fill('ada@collector.dev')
  await dialog.getByLabel('Senha', { exact: true }).fill('orchid-harbor')
  await dialog.locator('form').getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('heading', { name: /seja dono/i })).toBeVisible()

  await page.goto('/nfts/nft_01')
  await page.getByRole('button', { name: /comprar/i }).click()
  await expect(page.getByTestId('cart-item')).toBeVisible()
  await page.getByRole('link', { name: 'Conectar e finalizar' }).click()
  await expect(page.getByRole('heading', { name: 'Checkout' })).toBeVisible()
  await page.getByRole('checkbox', { name: /I confirm this total/ }).check()
  await page.getByRole('button', { name: /confirm purchase|confirmar compra/i }).click()
  const receipt = page.getByRole('dialog')
  await expect(receipt.getByTestId('order-status')).toHaveText('confirmed', { timeout: 15_000 })
  await expect(
    receipt.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' }),
  ).toBeVisible()
  await expect(receipt.getByTestId('tx-ref')).toHaveText(/^0x[0-9A-F]{4}…[0-9A-F]{4}$/)
  await expect(receipt.getByText(/ID do token: #/)).toBeVisible()
  await expect(receipt.getByText('Taxa de rede')).toBeVisible()
  await expect(receipt.getByText(/Transação confirmada na Ethereum/)).toBeVisible()
  const scan = receipt.getByRole('link', { name: 'Ver no Etherscan' })
  await expect(scan).toHaveAttribute('href', /https:\/\/etherscan\.io\/tx\/0x/)
  await expect(scan).toHaveAttribute('target', '_blank')
  await expect(scan).toHaveAttribute('rel', /noopener/)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeHidden()
})
